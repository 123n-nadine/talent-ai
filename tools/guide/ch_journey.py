def step(pid: str, title: str, img: str, cap: str, what: str, who: str, see: str, rely: str, example: str, behind: str,
         ids: list[str], nxt: str, terms: list[str] | None = None, extra_tech: list[str] | None = None, group: tuple[str, list[str]] | None = None,
         width: float = 1.0, crop: bool = True, top: float | None = None, h_cm: float | None = None) -> Page:
    blocks = [
        Img(img, cap, width, h_cm or 11.0, crop, top, fixed=bool(h_cm)),
        Field("إيه ده وليه", what),
        Field("مين", who),
        Field("هتشوفي إيه، من اليمين للشمال", see),
        Field("بنعتمد على إيه", rely),
        Field("مثال حقيقي", example),
        Field("ورا الكواليس", behind),
        Tech([line(i) for i in ids] + ([" ".join(code(i) for i in group[1]) + " " + group[0]] if group else []) + (extra_tech or [])),
        Field("وبعدها", nxt),
    ]
    return Page(pid, title, blocks, terms=terms or [], ids=ids + (group[1] if group else []))


