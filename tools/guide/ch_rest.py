def faq(F: dict) -> Chapter:
    pages, chunk = [], 6
    for i in range(0, len(FAQ), chunk):
        blocks = []
        for q, a in FAQ[i:i + chunk]:
            blocks += [Field("السؤال", q), P(a)]
        pages.append(Page(f"faq-{i // chunk + 1}", f"أسئلة متوقعة ({i // chunk + 1})", blocks))
    pages[0].terms = ["أسئلة متوقعة"]
    return Chapter("faq", "12 — أسئلة متوقعة وإجاباتها", pages)


